export type IconName = keyof typeof ICONS;

/** An inline pixel icon, `size` CSS pixels per icon pixel. */
export function icon(name: IconName, size = 2): string {
  const rows = ICONS[name];
  const w = Math.max(...rows.map((r) => r.length));
  let rects = "";
  rows.forEach((row, y) => [...row].forEach((c, x) => {
    if (c === "#") rects += `<rect x="${x}" y="${y}" width="1" height="1"/>`;
  }));
  return `<svg class="icon" aria-hidden="true" width="${w * size}" height="${rows.length * size}" viewBox="0 0 ${w} ${rows.length}" shape-rendering="crispEdges" fill="currentColor">${rects}</svg>`;
}
